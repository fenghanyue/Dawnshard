"""从游戏数据生成角色、龙的上线日期和卡池当年的开始日期，写到
DragaliaAPI/DragaliaAPI/Features/Summoning/ReleaseHistory.g.cs。
卡池的普通池按上线日期过滤时用（bannerConfig.json 的 FilterPoolByReleaseDate）。

游戏数据表里 2021 年以前出的角色，_ReleaseStartDate 都写成了 2021/01/01 06:00:00，不能用。上线日期这样定：
1. _ReleaseStartDate 不是 2021/01/01 06:00:00 的（2021 年以后出的），用它；
2. 否则用它第一次当卡池主打（SummonData 的 _PickupUnitId1~4）的那个卡池的开始日期；
3. 都没有的，当作开服就有，不写进表里。
2021 年以后出、当过主打的（51 个角色、16 条龙）有真实日期，拿第 2 条的算法去算，结果和 _ReleaseStartDate
全部一致，所以第 2 条可信。第 3 条里有些 3★/4★ 其实是后来出的，游戏数据里分不出来。

表里的日期是当年的原始日期。原作者会改 SummonData.json 来重开卡池，合并原作者的更新之后不要随手重新生成，
先确认 SummonData.json 里的日期还是当年的。

用法：python3 deploy/tencent/gen_release_dates.py
"""

import json
import re
import sys
from datetime import datetime
from pathlib import Path

HERE = Path(__file__).resolve().parent
SHARED = HERE.parent.parent / "DragaliaAPI" / "DragaliaAPI.Shared"
OUTPUT = HERE.parent.parent / "DragaliaAPI" / "DragaliaAPI" / "Features" / "Summoning" / "ReleaseHistory.g.cs"

PLACEHOLDER_RELEASE_DATE = "2021/01/01 06:00:00"
PICKUP_SLOTS = range(1, 5)


def read_json(relative_path: str):
    return json.loads((SHARED / "Resources" / relative_path).read_text(encoding="utf-8-sig"))


def enum_members(name: str) -> dict[int, str]:
    text = (SHARED / "Definitions" / "Enums" / f"{name}.cs").read_text(encoding="utf-8-sig")
    body = text.split(f"public enum {name}", 1)[1].split("}", 1)[0]
    return {int(value): member for member, value in re.findall(r"^\s*(\w+)\s*=\s*(\d+)", body, re.MULTILINE)}


def parse_date(text: str) -> datetime:
    # 游戏数据里的时间都是 UTC
    return datetime.strptime(text, "%Y/%m/%d %H:%M:%S")


def release_dates(units: list[dict], names: dict[int, str], first_pickup: dict[int, datetime]) -> dict[str, datetime]:
    dates = {}
    for unit in units:
        if not unit["_IsPlayable"] or unit["_Id"] not in names:
            continue
        if unit["_ReleaseStartDate"] and unit["_ReleaseStartDate"] != PLACEHOLDER_RELEASE_DATE:
            dates[names[unit["_Id"]]] = parse_date(unit["_ReleaseStartDate"])
        elif unit["_Id"] in first_pickup:
            dates[names[unit["_Id"]]] = first_pickup[unit["_Id"]]
    return dates


def csharp_date(date: datetime) -> str:
    return f"new({date.year}, {date.month}, {date.day}, {date.hour}, {date.minute}, {date.second}, TimeSpan.Zero)"


def dictionary(name: str, key_type: str, entries: list[tuple[str, datetime]], summary: str) -> str:
    lines = [
        "    /// <summary>",
        f"    /// {summary}",
        "    /// </summary>",
        f"    public static FrozenDictionary<{key_type}, DateTimeOffset> {name} {{ get; }} =",
        f"        new Dictionary<{key_type}, DateTimeOffset>",
        "        {",
    ]
    lines += [f"            [{key}] = {csharp_date(date)}," for key, date in entries]
    lines += ["        }.ToFrozenDictionary();"]
    return "\n".join(lines)


def main() -> int:
    summons = read_json("Summon/SummonData.json")
    first_pickup: dict[int, datetime] = {}
    for summon in summons:
        start = parse_date(summon["_CommenceDate"])
        for slot in PICKUP_SLOTS:
            unit_id = summon[f"_PickupUnitId{slot}"]
            if unit_id and (unit_id not in first_pickup or start < first_pickup[unit_id]):
                first_pickup[unit_id] = start

    charas = release_dates(read_json("CharaData.json"), enum_members("Charas"), first_pickup)
    dragons = release_dates(read_json("DragonData.json"), enum_members("DragonId"), first_pickup)
    banners = sorted((summon["_Id"], parse_date(summon["_CommenceDate"])) for summon in summons)

    def by_date(dates: dict[str, datetime], enum_name: str) -> list[tuple[str, datetime]]:
        return [(f"{enum_name}.{name}", date) for name, date in sorted(dates.items(), key=lambda x: (x[1], x[0]))]

    source = "\n".join(
        [
            "// <auto-generated>",
            "// Generated by deploy/tencent/gen_release_dates.py from the master data in DragaliaAPI.Shared/Resources.",
            "// Do not edit by hand.",
            "// </auto-generated>",
            "",
            "using System.Collections.Frozen;",
            "using DragaliaAPI.Shared.Definitions.Enums;",
            "",
            "namespace DragaliaAPI.Features.Summoning;",
            "",
            "/// <summary>",
            "/// Dates from the original game: when units were released and when banners started.",
            "/// </summary>",
            "/// <remarks>",
            "/// Release dates before 2021 are the start of the first banner a unit was on rate up in, since the master data",
            "/// gives every unit released before 2021 the same placeholder date. Units missing from the release dates were",
            "/// never on rate up: treat them as available from launch.",
            "/// </remarks>",
            "public static class ReleaseHistory",
            "{",
            dictionary(
                "CharaReleaseDates",
                "Charas",
                by_date(charas, "Charas"),
                "Gets the release dates of adventurers.",
            ),
            "",
            dictionary(
                "DragonReleaseDates",
                "DragonId",
                by_date(dragons, "DragonId"),
                "Gets the release dates of dragons.",
            ),
            "",
            dictionary(
                "BannerStartDates",
                "int",
                [(str(banner_id), start) for banner_id, start in banners],
                "Gets the original start dates of banners, keyed by banner ID.",
            ),
            "}",
            "",
        ]
    )
    OUTPUT.write_text(source, encoding="utf-8")
    print(f"已生成 {OUTPUT.relative_to(HERE.parent.parent)}：角色 {len(charas)} 个，龙 {len(dragons)} 个，卡池 {len(banners)} 个")
    return 0


if __name__ == "__main__":
    sys.exit(main())
